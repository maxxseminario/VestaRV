#*****************************************************************************
# extprobe_template.S   (ISA extension program, X0 scaffolding, 2026-07-16)
#-----------------------------------------------------------------------------
# TEMPLATE — NOT wired into any Makefrag or the xrun_parallel TEST_FILES array.
# A future phase agent (X1-X4) COPIES this to a real test name (e.g.
# extzicond.S) and fills in the encoding + result check for its extension.
#
# Why a NEW idiom (vs. the misa-dispatch extmul.S/extdiv.S/... poisons):
#   The existing ext* probes read the misa CSR (0x301) and branch on an
#   extension LETTER bit (M/A/C/B). That works for the base extensions, but the
#   RISC-V Z-EXTENSIONS SCAFFOLDED IN X0 (Zicond, Zcb, Zimop, Zihint, Zihpm,
#   Zawrs, Zabha, Zacas, Zbkb, Zbkc, Zbkx, Zkn, Zfinx) HAVE NO misa BIT — misa
#   is unchanged by any of them. So misa-dispatch CANNOT tell whether the chip
#   was built with the extension. Instead, dispatch at BUILD TIME on the
#   generator's CORE_ENABLE_<EXT> C-header #define:
#     #define present  == the chip was built with the extension ON
#     #define absent    == OFF  (the encoding must trap illegal-instruction)
#   generate.py emits `#define CORE_ENABLE_<EXT>` ONLY when the generic is true
#   (ChipGenerator.py, the "Core ISA features" #define block), so `#ifdef` is
#   the exact on/off test.
#
# WHERE THE HEADER LANDS / HOW TO INCLUDE IT:
#   The CORE_ENABLE_* defines live in the `make chip` product
#       platform/common/out/software/include/MemoryMap.h
#   (regenerated by `cd platform/common && make chip`; a #define appears there
#   for each extension whose generic is true). The default ISA-test compile
#   line (verification/isa/Makefile, compile_template) is:
#       -I../env/p -I./macros/scalar -I../../platform/myshkin/gcc/lib/include
#   NOTE: that pulls in the FROZEN Myshkin MemoryMap.h, which does NOT carry the
#   Castalia CORE_ENABLE_* defines. To dispatch on them, the phase agent adds
#   the Castalia/common header dir to that suite's compile flags, e.g.
#       -I$(src_dir)/../../platform/common/out/software/include
#   placed BEFORE the myshkin -I so its MemoryMap.h wins, OR stages a copy of
#   the generated header onto ../env/p. Whichever is chosen, the header must be
#   REBUILT (`make chip`) for the config under test — a stale header lies about
#   the build. (If wiring a new include path is undesirable, the fallback is a
#   trap-and-recover try-execute like the extmul.S off-arm below, keyed on a
#   mtvec handler — but the #define path is preferred: it needs no trap plumbing
#   for the ON arm and matches the both-polarity build discipline.)
#
# BOTH ARMS (this file is a WORKED EXAMPLE for Zicond czero.eqz/czero.nez):
#   feature ON  (#ifdef CORE_ENABLE_ZICOND):  execute the real encoding, CHECK
#                                             the architectural result, PASS.
#   feature OFF (#else):                       fall INTO the encoding; it MUST
#                                             take the illegal-instruction trap.
#                                             The negative-control harness
#                                             (behavioral_mp_stripped/run_extoff.sh
#                                             + trap_watch.tcl) reports that as
#                                             TRAP_OK; executing PAST it -> FAIL.
#
#   Encodings are emitted with `.insn` / `.word` so the file assembles under the
#   suite's base -march (the extension is NOT in -march). Whole-file
#   norvc/norelax keeps the image to fixed-width base + explicit encodings.
#*****************************************************************************

#include "riscv_test.h"
#include "test_macros.h"

# The generated Castalia header carrying CORE_ENABLE_<EXT> (see the include-path
# note above). A phase agent adds -I.../platform/common/out/software/include to
# this suite's flags; until then this include resolves to the Myshkin header,
# which lacks the Z-extension defines, so every arm below takes the OFF path.
#include "MemoryMap.h"

.option norvc
.option norelax

RVTEST_RV32U
RVTEST_CODE_BEGIN

    # ---- base-ISA sanity (runs on every build, like extprobe.S) ----
    li   t0, 1234
    li   t1, 4321
    add  t2, t0, t1
    li   t3, 5555
    bne  t2, t3, extt_fail

#ifdef CORE_ENABLE_ZICOND
    # =====================================================================
    # FEATURE ON: execute the real encoding and CHECK the result -> PASS.
    # czero.eqz rd,rs1,rs2 : rd = (rs2==0) ? 0 : rs1   (OP 0110011, f3=101, f7=0000111)
    # czero.nez rd,rs1,rs2 : rd = (rs2!=0) ? 0 : rs1   (OP 0110011, f3=111, f7=0000111)
    # =====================================================================
    li   a0, 0xABCD1234          # rs1 payload

    # czero.eqz a2, a0, a1  with rs2==0  -> a2 = 0
    li   a1, 0
    .insn r 0x33, 0x5, 0x07, a2, a0, a1
    bnez a2, extt_fail
    # czero.eqz a2, a0, a1  with rs2!=0  -> a2 = a0
    li   a1, 1
    .insn r 0x33, 0x5, 0x07, a2, a0, a1
    bne  a2, a0, extt_fail

    # czero.nez a2, a0, a1  with rs2!=0  -> a2 = 0
    li   a1, 7
    .insn r 0x33, 0x7, 0x07, a2, a0, a1
    bnez a2, extt_fail
    # czero.nez a2, a0, a1  with rs2==0  -> a2 = a0
    li   a1, 0
    .insn r 0x33, 0x7, 0x07, a2, a0, a1
    bne  a2, a0, extt_fail

    RVTEST_PASS

#else
    # =====================================================================
    # FEATURE OFF: the same encoding MUST take the illegal-instruction trap.
    # Surviving PAST it means misa/decode/gating disagree -> explicit FAIL.
    # (The stripped-build harness watches trap_flag via trap_watch.tcl and
    #  reports TRAP_OK when the trap fires here.)
    # =====================================================================
    li   a0, 0xABCD1234
    li   a1, 0
    .insn r 0x33, 0x5, 0x07, a2, a0, a1   # czero.eqz — must be illegal here
    j    extt_fail                        # reached only if the encoding did NOT trap

#endif

extt_fail:
    RVTEST_FAIL                 # a0 = 0xDEADBEEF

    # NOTE: RVTEST_CODE_END is 'unimp' (traps) in this env — never fall through.
    RVTEST_CODE_END

  .data
RVTEST_DATA_BEGIN
  TEST_DATA
extt_scratch: .word 0
RVTEST_DATA_END
