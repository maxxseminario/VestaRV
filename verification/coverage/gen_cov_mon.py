#!/usr/bin/python3.6
"""VestaRV: generate the coverage monitor and the two simulation tops.

    gen_cov_mon.py <repo root> <NHARTS> <output dir>

Nothing under hdl/ changes. The monitor is a second top-level branch that reads the
core through Xcelium's xm_mirror (library xmutils), so it can see signals that VHDL
cannot reach across hierarchy without external names, and it has no output into the
design. Xcelium's FSM coverage answers "was this state reached"; this adds what the
tool cannot express for a VHDL design: the hand-defined crosses, per hart, and a
second, independently derived state and transition table to check the tool against.

The enum literals are copied out of vesta.vhd and mp_arbiter.vhd at generation time
rather than transcribed here, so a state added to the core cannot be missed. xm_mirror
copies enum values by position, so a mirrored type must match its source in order
and count, which holds by construction when the list is the source's own.
"""

import os
import re
import sys

# 29 characters: riscv_tb's TEST_FILE generic is a fixed string(1 to 29). One snapshot
# serves every test because this path is relative: each test runs in its own directory,
# whose ../cur/ holds this name as a link to that test's image.
TEST_FILE = '../cur/' + 'x' * 18 + '.rcf'
assert len(TEST_FILE) == 29


def enum_literals(path, type_name):
    src = open(path, encoding='utf-8', errors='replace').read()
    src = re.sub(r'--[^\n]*', '', src)   # comments inside the enum carry parentheses
    m = re.search(r'type\s+%s\s+is\s*\((.*?)\)\s*;' % type_name, src, re.S | re.I)
    if not m:
        raise SystemExit('no type %s in %s' % (type_name, path))
    return [t.strip() for t in m.group(1).split(',') if t.strip()]


HART_MON = '''-- Generated by verification/coverage/gen_cov_mon.py. Do not edit.
library ieee;
use ieee.std_logic_1164.all;
library xmutils;
use xmutils.xmutilities.all;
use std.textio.all;

entity cov_hart_mon is
    generic (
        HART : natural;
        CORE : string;   -- absolute path of this hart's vesta instance
        TILE : string;   -- absolute path of this hart's hart_tile instance
        ARB  : string    -- absolute path of mp_arbiter
    );
    port (dump : in std_logic);
end entity;

architecture observer of cov_hart_mon is
    type cpu_state is (%(states)s);
    type arb_state is (%(arb)s);
    signal st       : cpu_state;
    signal arb_st   : arb_state;
    signal arb_cur  : natural := 0;
    signal clk      : std_logic;   -- this hart's gated clk_cpu
    signal mclk     : std_logic;   -- the arbiter's free-running clock
    signal irq_save : std_logic;
    signal sh_sel   : std_logic;
    signal amo_lock : std_logic;
begin
    setup: process
    begin
        xm_mirror("st",       CORE & ":current_state", "");
        xm_mirror("clk",      CORE & ":clk_cpu",       "");
        xm_mirror("irq_save", CORE & ":irq_save",      "");
        xm_mirror("amo_lock", CORE & ":amo_lock",      "");
        xm_mirror("sh_sel",   TILE & ":sh_sel",        "");
        xm_mirror("mclk",     ARB  & ":clk",           "");
        xm_mirror("arb_st",   ARB  & ":state",         "");
        xm_mirror("arb_cur",  ARB  & ":cur",           "");
        wait;
    end process;

    -- Sampled on clk_cpu, a stalled state shows once, at the edge that releases it, by which
    -- time the arbiter has moved on. n_arbm samples the same cross on mclk, so every cycle a
    -- transaction spends in a state is seen against the arbiter as it stood in that cycle.
    count: process(clk, mclk, dump)
        type vec_t   is array (cpu_state) of natural;
        type mat_t   is array (cpu_state, cpu_state) of natural;
        type bit_t   is array (cpu_state, std_ulogic range '0' to '1') of natural;
        type arbx_t  is array (cpu_state, arb_state, boolean) of natural;
        variable n_st   : vec_t  := (others => 0);
        variable n_tr   : mat_t  := (others => (others => 0));
        variable n_irq  : bit_t  := (others => (others => 0));
        variable n_sh   : bit_t  := (others => (others => 0));
        variable n_lock : bit_t  := (others => (others => 0));
        variable n_arb  : arbx_t := (others => (others => (others => 0)));
        variable n_arbm : arbx_t := (others => (others => (others => 0)));
        variable prev   : cpu_state;
        variable first  : boolean := true;
        file     f      : text;
        variable l      : line;

        procedure emit(tag, a, b, c : string; n : natural) is
        begin
            if n /= 0 then
                write(l, tag & " " & a & " " & b & " " & c & " " & integer'image(n));
                writeline(f, l);
            end if;
        end procedure;
    begin
        if rising_edge(clk) then
            n_st(st) := n_st(st) + 1;
            if not first then
                n_tr(prev, st) := n_tr(prev, st) + 1;
            end if;
            first := false;
            prev  := st;
            n_irq(st, to_x01(irq_save)) := n_irq(st, to_x01(irq_save)) + 1;
            n_sh(st, to_x01(sh_sel))    := n_sh(st, to_x01(sh_sel)) + 1;
            n_lock(st, to_x01(amo_lock)) := n_lock(st, to_x01(amo_lock)) + 1;
            n_arb(st, arb_st, arb_cur = HART) := n_arb(st, arb_st, arb_cur = HART) + 1;
        end if;
        if rising_edge(mclk) then
            n_arbm(st, arb_st, arb_cur = HART) := n_arbm(st, arb_st, arb_cur = HART) + 1;
        end if;
        if rising_edge(dump) then
            file_open(f, "mon_h" & integer'image(HART) & ".txt", write_mode);
            for s in cpu_state loop
                emit("ST", cpu_state'image(s), "-", "-", n_st(s));
                for d in cpu_state loop
                    emit("TR", cpu_state'image(s), cpu_state'image(d), "-", n_tr(s, d));
                end loop;
                for b in std_ulogic range '0' to '1' loop
                    emit("IRQ",  cpu_state'image(s), std_ulogic'image(b), "-", n_irq(s, b));
                    emit("SH",   cpu_state'image(s), std_ulogic'image(b), "-", n_sh(s, b));
                    emit("LOCK", cpu_state'image(s), std_ulogic'image(b), "-", n_lock(s, b));
                end loop;
                for a in arb_state loop
                    emit("ARB", cpu_state'image(s), arb_state'image(a), "self",  n_arb(s, a, true));
                    emit("ARB", cpu_state'image(s), arb_state'image(a), "other", n_arb(s, a, false));
                    emit("ARBM", cpu_state'image(s), arb_state'image(a), "self",  n_arbm(s, a, true));
                    emit("ARBM", cpu_state'image(s), arb_state'image(a), "other", n_arbm(s, a, false));
                end loop;
            end loop;
            file_close(f);
        end if;
    end process;
end architecture;
'''

TOPS = '''-- Generated by verification/coverage/gen_cov_mon.py. Do not edit.
library ieee;
use ieee.std_logic_1164.all;

-- Uninstrumented reference: exactly what a per-test wrapper of xrun_parallel.sh is.
entity base_top is end entity;
architecture behavioral of base_top is
begin
    uut: entity work.riscv_tb generic map (TEST_FILE => "%(test_file)s");
end architecture;

library ieee;
use ieee.std_logic_1164.all;

entity cov_top is end entity;
architecture behavioral of cov_top is
    signal mon_dump : std_logic := '0';   -- deposited by the batch tcl after the run
begin
    uut: entity work.riscv_tb generic map (TEST_FILE => "%(test_file)s");
%(mons)s
end architecture;
'''

MON_INST = '''    mon%(h)d: entity work.cov_hart_mon
        generic map (HART => %(h)d, CORE => "%(tile)s:core", TILE => "%(tile)s",
                     ARB => ":uut:dut:mp_arb0")
        port map (dump => mon_dump);
'''


def main():
    root, nharts, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    states = enum_literals(os.path.join(root, 'hdl/common/vesta/vesta.vhd'), 'cpu_state')
    arb = enum_literals(os.path.join(root, 'hdl/common/mp_arbiter.vhd'), 'state_t')
    with open(os.path.join(out, 'cov_hart_mon.vhd'), 'w') as f:
        f.write(HART_MON % {'states': ', '.join(states), 'arb': ', '.join(arb)})
    mons = ''
    for h in range(nharts):
        # Hart 0 is orch_tile, a thin wrapper around one hart_tile labelled `tile`.
        tile = ':uut:dut:hart0:tile' if h == 0 else ':uut:dut:hart%d' % h
        mons += MON_INST % {'h': h, 'tile': tile}
    with open(os.path.join(out, 'cov_tops.vhd'), 'w') as f:
        f.write(TOPS % {'test_file': TEST_FILE, 'mons': mons})
    with open(os.path.join(out, 'cpu_states.txt'), 'w') as f:
        f.write('\n'.join(states) + '\n')
    print('monitor: %d cpu_state literals, %d arbiter states, %d harts'
          % (len(states), len(arb), nharts))


if __name__ == '__main__':
    main()
