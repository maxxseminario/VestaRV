# --------------------------------------------------------------------------
# harness
# --------------------------------------------------------------------------

class Harness(object):
    def __init__(self):
        self.dir = tempfile.mkdtemp(prefix="cosim_selftest_")
        self.passed = 0
        self.failed = 0
        self.n = 0

    def cleanup(self):
        shutil.rmtree(self.dir, ignore_errors=True)

    def write(self, name, lines):
        path = os.path.join(self.dir, name)
        with open(path, "w") as fh:
            fh.write("".join(lines))
        return path

    def compare(self, rtl_lines, spike_lines, extra=(), tag="t"):
        rtl = self.write("%s.trace" % tag, rtl_lines)
        spk = self.write("%s.spike.log" % tag, spike_lines)
        cmd = [PY, COMPARE, "--rtl", rtl, "--spike", spk, "--entry", "0x8200"]
        cmd += list(extra)
        p = subprocess.Popen(cmd, stdout=subprocess.PIPE,
                             stderr=subprocess.PIPE)
        so, se = p.communicate()
        return p.returncode, so.decode(), se.decode(), cmd

    def case(self, name, expect, rtl_lines, spike_lines, extra=(),
             expect_in_stdout=None, expect_in_stderr=None):
        self.n += 1
        tag = "c%02d" % self.n
        rc, so, se, cmd = self.compare(rtl_lines, spike_lines, extra, tag)
        why = []
        if rc != expect:
            why.append("exit %d, expected %d" % (rc, expect))
        for needle in (expect_in_stdout or []):
            if needle not in so:
                why.append("stdout missing %r" % needle)
        for needle in (expect_in_stderr or []):
            if needle not in se:
                why.append("stderr missing %r" % needle)
        self.report(name, expect, rc, why, so, se, cmd)
        return rc, so, se

    def raw(self, name, cmd, expect, expect_in_stderr=None):
        self.n += 1
        p = subprocess.Popen(cmd, stdout=subprocess.PIPE,
                             stderr=subprocess.PIPE)
        so, se = p.communicate()
        so, se = so.decode(), se.decode()
        why = []
        if p.returncode != expect:
            why.append("exit %d, expected %d" % (p.returncode, expect))
        for needle in (expect_in_stderr or []):
            if needle not in se:
                why.append("stderr missing %r" % needle)
        self.report(name, expect, p.returncode, why, so, se, cmd)
        return p.returncode, so, se

    def check(self, name, ok, detail=""):
        self.n += 1
        self.report(name, "ok", "ok" if ok else "FAIL",
                    [] if ok else [detail or "assertion failed"], "", "", None)

    def report(self, name, expect, got, why, so, se, cmd):
        if not why:
            self.passed += 1
            print("PASS  %-52s exit=%s" % (name, got))
        else:
            self.failed += 1
            print("FAIL  %-52s exit=%s (want %s)" % (name, got, expect))
            for w in why:
                print("        %s" % w)
            if cmd:
                print("        cmd: %s" % " ".join(cmd))
            for stream, text in (("stdout", so), ("stderr", se)):
                for line in text.splitlines()[:24]:
                    print("        %s| %s" % (stream[:3], line))


