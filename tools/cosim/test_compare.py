def sub(lines, index, old, new):
    """Copy `lines` with a substring replaced on one line (fixture mutation)."""
    out = list(lines)
    assert old in out[index], "fixture drift: %r not in %r" % (old, out[index])
    out[index] = out[index].replace(old, new)
    return out


