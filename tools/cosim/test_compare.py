    # ---------------- Amendment A16: the ghost is gone at SOURCE ---------
    # Same failed sc.w, same reference, post-A16 trace. Two things must hold and
    # the second is the point of the amendment:
    #   * A15 finds nothing to drop and says WHY it found nothing -- naming
    #     A16, not the pre-A16 "the core declined the write locally", which
    #     would be a false statement about every cross-hart kill;
    #   * the `--no-a15` NEGATIVE CONTROL becomes INERT. V4 proved A15
    #     load-bearing by flipping this control 0 -> 1. That it no longer flips
    #     is the evidence that A16 removed the shape at source rather than
    #     moving numbers: the comparator no longer NEEDS the exception.
    h.case("exit0 A16 post-fix trace: no ghost to drop, and the note says A16",
           0, [HEADER] + A16_FAIL_RTL, A15_FAIL_SPIKE,
           expect_in_stderr=["0 ghost store(s) dropped",
                             "[# SCGHOST, Amendment A16]"])
    h.case("exit0 A16 makes --no-a15 INERT (V4's control flipped 0->1; now 0->0)",
           0, [HEADER] + A16_FAIL_RTL, A15_FAIL_SPIKE, extra=("--no-a15",))
    # And the shim is NOT dead: the pre-A16 trace still needs A15, both polarities.
    h.case("exit0 A15 SHIM still drops the ghost in a PRE-A16 trace",
           0, [HEADER] + A15_FAIL_RTL, A15_FAIL_SPIKE,
           expect_in_stderr=["1 ghost store(s) dropped"])
    h.case("exit1 A15 SHIM off + PRE-A16 trace still diverges (control alive)",
           1, [HEADER] + A15_FAIL_RTL, A15_FAIL_SPIKE, extra=("--no-a15",))

    # ---- §6.1 test_bracket_interior_load_dropped (A13's PARTITION) -------
    # This one tests mk_inject.py, not compare.py, but it belongs with the other
    # bracket tests: it pins the half of A13 that FIXES V3's structural hole.
    # An unmodelled-region load INSIDE a bracket must be DROPPED from the mainline
    # replay list (the reference never executes the interior, so it never asks for
    # the value and V3's emitted entry made vesta_ref die with exit 7
    # INJECT-MISMATCH), and the drop must be COUNTED, never silent.
    mkinj = os.path.join(HERE, "mk_inject.py")
    tdir = tempfile.mkdtemp(prefix="cosim_a13_")
    try:
        tr = os.path.join(tdir, "t_h00.trace")
        with open(tr, "w") as fh:
            fh.write(HEADER)
            fh.writelines([
                # one MMIO load OUTSIDE any bracket -> must be KEPT
                "R 00 00000010 00008200 00012083 01 000000aa\n",
                "M 00 00000010 L 00004204 4 000000aa\n",
                # a park, then an MMIO load and a plant-window load INSIDE it
                "X 00 00000011 wfi_enter\n",
                "R 00 00000012 000002b4 0000100b 00 00000000\n",
                "T 00 00000013 8000007f 000002b8 0000814c 3\n",
                "R 00 00000014 0000814c 00008067 00 00000000\n",
                "M 00 00000014 L 00004204 4 000000bb\n",       # interior MMIO
                "R 00 00000015 00000300 00012083 01 000000cc\n",
                "M 00 00000015 L 00010500 4 000000cc\n",       # interior PLANT
                "M 00 00000016 S 00008000 4 deadbeef\n",
                "# IRETPOP 00 00000017 0000bff8\n",
                "X 00 00000017 iret\n",
                "R 00 00000018 000082fc 00012083 01 000000dd\n",
                "M 00 00000018 L 00010504 4 000000dd\n",       # mainline PLANT
            ])
        inj = os.path.join(tdir, "t.inject"); brk = os.path.join(tdir, "t.bracket")
        p = subprocess.Popen(
            [PY, mkinj, "--rtl", tr, "-o", inj, "--bracket-out", brk,
             "--mmio", "0x4000:0x4000", "--plant", "0xc000:0x14000"],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        _, se = p.communicate(); se = se.decode()
        ilines = [l.split() for l in open(inj) if l.strip() and not l.startswith("#")]
        blines = open(brk).read()
        h.check("A13 the OUTSIDE-bracket MMIO load is kept in the inject list",
                len(ilines) == 1 and ilines[0][0] == "00004204",
                "inject list = %r (want exactly the 00004204 record)" % (ilines,))
        h.check("A13 the INTERIOR MMIO load is DROPPED from the inject list",
                all(l[2] != "000000bb" for l in ilines),
                "the interior value 000000bb reached the mainline list: %r" % (ilines,))
        h.check("A13 the INTERIOR plant-window load emits no mainline P record",
                "P 1 00010500" not in blines and "00010500" not in
                "\n".join(l for l in blines.splitlines() if l.startswith("P ")),
                "an interior plant leaked into a P record")
        h.check("A13 the MAINLINE plant-window load DOES emit a P record",
                any(l.startswith("P ") and "00010504" in l
                    for l in blines.splitlines()),
                "the post-bracket plant is missing from %s" % brk)
        h.check("A13 the drop is COUNTED, never silent (census + annotation)",
                "DROPPED" in blines and "census:" in blines
                and "dropped load(s)" in se,
                "no DROPPED annotation / census; stderr was:\n%s" % se)
        h.check("A13 the census separates mmio from plant drops exactly",
                "1 mmio + 1 plant" in blines,
                "census does not read '1 mmio + 1 plant':\n%s"
                % "\n".join(l for l in blines.splitlines() if "census" in l))
    finally:
        shutil.rmtree(tdir, ignore_errors=True)

    # ---- A16 in mk_inject: the `ext` failure shape gets a real witness ---
    # Pre-A16 the injector inferred "resv_unit suppressed the write" from THE
    # PRESENCE OF A FOLLOWING STORE -- i.e. it read the defect A15 exists to
    # delete as its own instrument, so after A16 that census would silently
    # read 0. It now counts `# SCGHOST`. Both legs are exercised, because a
    # counter that has only ever been seen at 0 has not been tested (R-W4-2):
    #   leg 1  rd=1 + # SCGHOST      -> ext-shape=1, and NO warning
    #   leg 2  rd=0 + # SCGHOST      -> the new cross-check FIRES
    # Leg 2's shape cannot occur in the RTL (the core computes rd FROM
    # sc_fail_ext), which is exactly why it needs a fixture: it is the check
    # that would otherwise be added to the tool having never once run.
    tdir = tempfile.mkdtemp(prefix="cosim_a16_")
    try:
        for leg, rdval, want_ext, want_warn in (
                ("rd=1", "00000001", "ext-shape=1", False),
                ("rd=0", "00000000", "ext-shape=0", True)):
            tr = os.path.join(tdir, "g_h00.trace")
            with open(tr, "w") as fh:
                fh.write(HEADER)
                fh.writelines([
                    "# SCGHOST 00 00000040 0001000c 4 000015b3\n",
                    "R 00 00000040 00008200 19c2aeaf 1d %s\n" % rdval,
                    "R 00 00000042 00008204 4081 01 00000000\n",
                ])
            inj = os.path.join(tdir, "g.inject")
            brk = os.path.join(tdir, "g.bracket")
            p = subprocess.Popen(
                [PY, mkinj, "--rtl", tr, "-o", inj, "--bracket-out", brk,
                 "--mmio", "0x4000:0x4000", "--plant", "0xc000:0x14000"],
                stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            _, se = p.communicate(); se = se.decode()
            h.check("A16 mk_inject counts # SCGHOST as the ext shape (%s)" % leg,
                    want_ext in se,
                    "census does not read %r; stderr was:\n%s" % (want_ext, se))
            fired = "SCGHOST" in se and "claims success" in se
            h.check("A16 rd/SCGHOST disagreement %s (%s)"
                    % ("is REPORTED" if want_warn else "is silent", leg),
                    fired == want_warn,
                    "warning %s; stderr was:\n%s"
                    % ("missing" if want_warn else "fired unexpectedly", se))
    finally:
        shutil.rmtree(tdir, ignore_errors=True)

    # ---- A13/A6 SUB-WORD PLANT LANE SELECT (vesta_ref) -------------------
    # A real bug, caught only by the full sh* suite: an `M ... L` data field is the
    # RAW BUS WORD (A6), so a plant of `size` bytes at `addr` must poke
    #     word >> 8*(addr mod 4)
    # not the word's low bytes. An `M ... S` data field is right-justified (§2), so
    # S must NOT be shifted -- the two record kinds genuinely differ, which is why
    # this went unnoticed while every Stage 2-5 shared access was word-wide.
    # Verified by EXECUTION against the built reference, both polarities, using the
    # verbatim numbers from rv32ui-p-shmem hart 0.
    vref = os.path.join(os.path.dirname(HERE), "..", "xcelium", "riscv_test",
                        "behavioral_mp", "cosim_work", "vesta_ref")
    vref = os.path.abspath(vref)
    env_sh = os.path.expanduser("~/local/spike_env.sh")
    if os.path.exists(vref) and os.path.exists(env_sh):
        tdir = tempfile.mkdtemp(prefix="cosim_lane_")
        try:
            # A 2-instruction RAM program at 0x8000:  lbu t2,9(t0) ; nop
            # t0 starts 0, so 9(t0) is address 0x9 -- inside --mem, byte offset 1.
            prog = os.path.join(tdir, "p.bin")
            with open(prog, "wb") as fh:
                #  0092c383 = lbu t2,9(t0)      0x00000013 = nop
                fh.write(b"\x83\xc3\x92\x00" + b"\x13\x00\x00\x00")
            inj = os.path.join(tdir, "e.inject")
            open(inj, "w").write("")           # no MMIO loads at all
            brk = os.path.join(tdir, "p.bracket")
            # plant the RAW WORD beef33ee for a 1-byte load at 0x9:
            # the addressed byte is (0xbeef33ee >> 8*(9 mod 4)) & 0xff = 0x33.
            open(brk, "w").write("P 0 00000009 1 beef33ee\n")
            log = os.path.join(tdir, "c.log")
            cmd = (". %s; %s cosim --rom %s --rom-base 0x0 --rom-format bin "
                   "--pc 0x8000 --mem 0x0:0x20000 --mmio 0x4000:0x4000 "
                   "--isa rv32imac_zicsr --priv m --instructions 1 "
                   "--inject %s --bracket %s --log %s"
                   % (env_sh, vref, prog, inj, brk, log))
            # --rom loads at 0x0; move the program to 0x8000 by padding instead.
            with open(prog, "wb") as fh:
                fh.write(b"\x00" * 0x8000 + b"\x83\xc3\x92\x00" + b"\x13\x00\x00\x00")
            p = subprocess.Popen(["bash", "-c", cmd], stdout=subprocess.PIPE,
                                 stderr=subprocess.PIPE)
            _, se = p.communicate()
            body = open(log).read() if os.path.exists(log) else ""
            h.check("A13/A6 a sub-word plant serves the ADDRESSED lane, not the low byte",
                    "0x00000033" in body,
                    "lbu t2,9(t0) with plant word beef33ee must commit x7=0x33; "
                    "0x000000ee means the lane select is missing. log=%r stderr=%r"
                    % (body.strip()[:200], se.decode()[-300:]))
            h.check("A13/A6 negative control: the LOW byte 0xee is NOT what commits",
                    "0x000000ee" not in body,
                    "the reference committed 0xee -- the raw-word low byte -- so the "
                    "A6 lane select is not being applied")
        finally:
            shutil.rmtree(tdir, ignore_errors=True)
    else:
        print("SKIP  A13/A6 sub-word plant lane select (no built vesta_ref)")

    h.cleanup()
    print("")
    print("%d/%d cases passed" % (h.passed, h.passed + h.failed))
    return 0 if h.failed == 0 else 1


