#!/usr/bin/python3.6
"""emit.py -- turn a built stream into a `.S` file for verification/isa.

THE CENSUS CONTRACT
-------------------
Everything between the global symbols `k3_stream_begin` and `k3_stream_end` is
the CENSUS RANGE, and inside it exactly one rule holds:

    every emitted line assembles to exactly ONE machine instruction.

No pseudo-instructions (`li`, `la`, `mv`, `nop`, `ret`, `call`, `j`, `beqz`,
...), because `li` assembles to one OR TWO encodings depending on the constant
and a manifest counting "what I asked for" would then disagree with a census
counting "what is in the image" by a number nobody could predict.  Constants
inside the range are materialised with explicit `lui`/`addi`.  `.option norvc`
and `.option norelax` are pushed around the range so neither the assembler nor
the linker may re-encode anything.

Outside the range -- prologue, epilogue, ISR, data -- pseudo-instructions are
free, and are used, because nothing counts them.

The range is delimited by SYMBOLS rather than by marker instructions so that the
census reads its bounds out of the ELF symbol table: structurally determined,
with nothing to calibrate (method rule 7).

Python 3.6 compatible.
"""

import stream as _stream

VERSION = '1.2.0'
GENERATOR = 'k3-randgen'

_HDR = '''\
# See LICENSE for license details.

#*****************************************************************************
# {name}.S  --  GENERATED by tools/randgen ({gen} {ver}).  DO NOT HAND-EDIT.
#-----------------------------------------------------------------------------
# A K3 constrained-random RV32 instruction stream.  Regenerate byte-identically
# with:
#
#   /usr/bin/python3.6 tools/randgen/randgen.py gen \\
#       --name {name} --seed {seed} --profile {profile} --length {length}{obsflag}
#
# REPRODUCTION LINE (R-DK5 -- a finding without one is not a finding):
#   generator : {gen} {ver}
#   seed      : {seed}
#   profile   : {profile}
#   length    : {length} emitted instructions requested
#   config    : {cfgid}
#   reference : --isa {oisa} --priv {opriv} --pmpregions {opmp}
#
# WHAT A PASS OF THIS FILE IN THE BEHAVIORAL SUITE MEANS
#   The stream did not trap, it terminated, the two scratch base registers and
#   `sp` survived unchanged, and no store escaped the 256-byte scratch window
#   (32 guard words, verified in the epilogue).{irqclaim}
#   It says NOTHING about whether any computed value is correct.  That is the
#   lockstep comparator's job -- `s5_ledger.md` 2.3, "has-a-bench is not
#   has-coverage".
#
# STRUCTURAL INVARIANTS (a trap is TERMINAL on a default build -- TRAP_STATE
# self-loops with no ENABLE_ term, K0 oracle probe 1.3n -- so nothing here may
# rely on being caught afterwards):
#   * only encodings legal for the config above; `gas` re-checks under -march
#   * every memory access is `off(base)` with base in x8/x9, which no emitted
#     instruction ever writes, and `off` drawn to be in-window and aligned
#   * conditional branches and `jal` are FORWARD ONLY, so the body is a DAG;
#     the only backward transfer is a subroutine `jalr x0, 0(ra)` return
#   * `lr.w`/`sc.w` are emitted ONLY as an immediately-adjacent pair, and a
#     branch target can never land between them (labels sit at template
#     boundaries only)
#
# NOTE: `RVTEST_CODE_END` is `unimp` in this env (it TRAPS since F10) -- every
# path below ends in an explicit PASS or FAIL spin and never falls through.
#*****************************************************************************

#include "riscv_test.h"
#include "test_macros.h"

RVTEST_RV32U
RVTEST_CODE_BEGIN
'''


def _guard_lo(i):
    return _stream.GUARD_LO_MAGIC + i


def _guard_hi(i):
    return _stream.GUARD_HI_MAGIC + i


def required_march(cfg):
    """The `-march` this config's emitted classes need.

    Only the knobs this generator has emitters for appear; a knob that is ON but
    unemitted needs no march fragment because nothing is emitted for it (and it
    is named separately in the manifest, never silently dropped).
    """
    s = 'rv32i'
    if cfg.isa.get('mul') and cfg.isa.get('div'):
        s += 'm'
    if cfg.isa.get('atomics'):
        s += 'a'
    if cfg.isa.get('compressed'):
        s += 'c'
    if cfg.isa.get('bitmanip'):
        s += '_zba_zbb_zbc_zbs'
    return s


def _init_values(rng, n):
    """Deterministic seed values for the pool registers.

    A fixed spine of architecturally interesting constants first (0, -1,
    INT_MIN, INT_MAX, and two shift-edge values), then random 32-bit words.  The
    spine is what makes `div`'s INT_MIN/-1 and shift-by-31 paths reachable from
    the ordinary random draws as well as from `_e_div`'s explicit setup.
    """
    spine = [0x00000000, 0xFFFFFFFF, 0x80000000, 0x7FFFFFFF,
             0x00000001, 0x0000001F, 0xAAAAAAAA, 0x55555555]
    out = []
    for i in range(n):
        if i < len(spine):
            out.append(spine[i])
        else:
            out.append(rng.next_u32())
    return out


_NC_BANNER = '''\
#*****************************************************************************
# !!! K3 NEGATIVE CONTROL -- THIS STREAM IS EXPECTED TO **FAIL** !!!
#
#   kind : {kind}
#   what : {what}
#
# It exists so the epilogue's discipline checks can be SEEN TO FAIL (method
# rule 1: a detector never seen to fail proves nothing).  It is NOT one of the
# k3_spec.md item-6 acceptance mutants -- those target the generator's
# config-LEGALITY and are authored by a second agent that has not seen the
# generator.  Never put this file in a standing list.
#*****************************************************************************

'''


def render(builder, cfg, name, seed, profile, length, irq_observe):
    """The complete `.S` text."""
    rng = builder.rng
    L = []
    if builder.negctrl:
        L.append(_NC_BANNER.format(
            kind=builder.negctrl,
            what=builder.NEGCTRL[builder.negctrl]))
    irq_claim = ('\n#   For an IRQ profile it also means EVERY msip that was\n'
                 '#   actually raised (a dynamic count, kept in the reserved\n'
                 '#   scratch word at +%d) was taken and handled exactly once,\n'
                 '#   and that the number was not zero.  %d arm site(s) are\n'
                 '#   emitted; forward branches may skip some, which is why the\n'
                 '#   check compares two RUNTIME counters and not a static one.'
                 % (_stream.ARMED_OFF, builder.irq_sites)) \
        if (irq_observe and builder.irq_sites) else ''
    L.append(_HDR.format(
        name=name, gen=GENERATOR, ver=VERSION, seed=seed, profile=profile,
        length=length, cfgid=cfg.identity(), oisa=cfg.oracle_isa_string,
        opriv=cfg.oracle_priv, opmp=cfg.oracle_pmpregions,
        irqclaim=irq_claim,
        obsflag='' if irq_observe else ' \\\n#       --no-irq-observe'))

    # ---------------- prologue (pseudo-instructions allowed) --------------
    L.append('    # ---- prologue: establish the invariants the body relies on')
    L.append('    li   sp, 0x%X                 # IRQ_SV pushes the return PC '
             'at sp-4 (M5b)' % _stream.SP_INIT)
    L.append('    la   x%d, k3_scratch' % _stream.R_BASE_A)
    L.append('    la   x%d, k3_scratch' % _stream.R_BASE_B)
    L.append('    addi x%d, x%d, %d' % (_stream.R_BASE_B, _stream.R_BASE_B,
                                        _stream.BASE_B_OFF))
    if builder.irq_sites:
        L.append('    la   t0, k3_irq_count')
        L.append('    sw   x0, 0(t0)')
    L.append('')
    L.append('    # ---- deterministic seed values for the general pool')
    vals = _init_values(rng, len(_stream.POOL))
    for r, v in zip(_stream.POOL, vals):
        L.append('    li   x%-2d, 0x%08X' % (r, v))
    L.append('')

    # ---------------- the census range ------------------------------------
    L.append('    # ===================================================================')
    L.append('    # CENSUS RANGE.  Every line below assembles to exactly ONE')
    L.append('    # instruction: no pseudo-instructions, no compression, no')
    L.append('    # relaxation.  tools/randgen/census.py decodes exactly this')
    L.append('    # byte range out of the built ELF and must reproduce the')
    L.append('    # manifest counts exactly.')
    L.append('    # ===================================================================')
    L.append('    .option push')
    L.append('    .option norvc')
    L.append('    .option norelax')
    L.append('    .globl k3_stream_begin')
    L.append('k3_stream_begin:')
    for it in builder.items:
        if isinstance(it, _stream.Label):
            L.append('%s:' % it.name)
        else:
            L.append('    %s' % it.text)
    L.append('    .globl k3_stream_end')
    L.append('k3_stream_end:')
    L.append('    .option pop')
    L.append('')

    # ---------------- epilogue --------------------------------------------
    L.append('    # ---- epilogue: the discipline checks.  These are the ONLY')
    L.append('    # things that can turn this stream into a FAIL at the a0 gate.')
    L.append('    la   t0, k3_scratch')
    L.append('    bne  x%d, t0, k3_bad          # base A survived'
             % _stream.R_BASE_A)
    L.append('    addi t0, t0, %d' % _stream.BASE_B_OFF)
    L.append('    bne  x%d, t0, k3_bad          # base B survived'
             % _stream.R_BASE_B)
    L.append('    li   t0, 0x%X' % _stream.SP_INIT)
    L.append('    bne  sp, t0, k3_bad           # sp survived')
    L.append('    la   t0, k3_guard_lo')
    L.append('    li   t1, 0')
    L.append('    li   t3, 0x%08X' % _stream.GUARD_LO_MAGIC)
    L.append('1:  lw   t2, 0(t0)')
    L.append('    add  t4, t3, t1')
    L.append('    bne  t2, t4, k3_bad           # low guard intact')
    L.append('    addi t0, t0, 4')
    L.append('    addi t1, t1, 1')
    L.append('    li   t5, %d' % _stream.GUARD_WORDS)
    L.append('    bne  t1, t5, 1b')
    L.append('    la   t0, k3_guard_hi')
    L.append('    li   t1, 0')
    L.append('    li   t3, 0x%08X' % _stream.GUARD_HI_MAGIC)
    L.append('2:  lw   t2, 0(t0)')
    L.append('    add  t4, t3, t1')
    L.append('    bne  t2, t4, k3_bad           # high guard intact')
    L.append('    addi t0, t0, 4')
    L.append('    addi t1, t1, 1')
    L.append('    li   t5, %d' % _stream.GUARD_WORDS)
    L.append('    bne  t1, t5, 2b')
    if builder.irq_sites and irq_observe:
        L.append('    # Every msip that was ACTUALLY RAISED was taken and')
        L.append('    # handled exactly once.  The comparison is dynamic on')
        L.append('    # BOTH sides: forward branches skip arm sites, so the')
        L.append('    # static site count is NOT what executes.')
        L.append('    la   t0, k3_scratch')
        L.append('    lw   t1, %d(t0)               # armed (raised)'
                 % _stream.ARMED_OFF)
        L.append('    la   t0, k3_irq_count')
        L.append('    lw   t2, 0(t0)                # handled')
        L.append('    bne  t1, t2, k3_bad')
        L.append('    beq  t1, x0, k3_bad           # ...and at least one, so')
        L.append('                                  # the check is not vacuous')
    L.append('    RVTEST_PASS')
    L.append('')
    L.append('k3_bad:')
    L.append('    RVTEST_FAIL')
    L.append('')

    # ---------------- ISR + IVT -------------------------------------------
    if builder.irq_sites:
        L.append('    # ---- CLINT msip handler (IVT slot 83, hardware-vectored,')
        L.append('    # legacy delivery).  Clears the LEVEL before iret or the')
        L.append('    # handler re-triggers immediately.  t0/t1/t2 are saved so')
        L.append('    # the stream\'s pool registers are untouched.')
        L.append('k3_msip_isr:')
        L.append('    addi sp, sp, -12')
        L.append('    sw   t0, 0(sp)')
        L.append('    sw   t1, 4(sp)')
        L.append('    sw   t2, 8(sp)')
        L.append('    li   t0, 0x%X' % _stream.CLINT_MSIP0)
        L.append('    sw   x0, 0(t0)                # clear MSIP[0]')
        L.append('    la   t1, k3_irq_count')
        L.append('    lw   t2, 0(t1)')
        L.append('    addi t2, t2, 1')
        L.append('    sw   t2, 0(t1)')
        L.append('    lw   t0, 0(sp)')
        L.append('    lw   t1, 4(sp)')
        L.append('    lw   t2, 8(sp)')
        L.append('    addi sp, sp, 12')
        L.append('    iret')
        L.append('')
    L.append('    # ---- extend the env IVT: DEFINE_IVT emitted slots 0-82.')
    L.append('    .section .ivt, "ax"')
    L.append('    .org 0x14C')
    if builder.irq_sites:
        L.append('    jal  zero, k3_msip_isr        # 83 msip')
    else:
        L.append('    jal  zero, 0x0BB00            # 83 msip: parked')
    L.append('    jal  zero, 0x0BB00            # 84 mtip: parked')
    L.append('    jal  zero, 0x0BB00            # 85 meip: parked')
    L.append('    .previous')
    L.append('')
    L.append('    RVTEST_CODE_END')
    L.append('')

    # ---------------- data -------------------------------------------------
    L.append('  .data')
    L.append('RVTEST_DATA_BEGIN')
    L.append('')
    L.append('  TEST_DATA')
    L.append('')
    L.append('RVTEST_DATA_END')
    L.append('')
    L.append('    # 64-byte-aligned, 64-byte-guarded on both sides.  `.data`')
    L.append('    # (initialised) and not `.bss`, so BOTH the RTL image and the')
    L.append('    # reference ELF carry real bytes rather than relying on')
    L.append('    # either side\'s zero-fill convention.')
    L.append('    .align 6')
    L.append('k3_guard_lo:')
    for i in range(_stream.GUARD_WORDS):
        L.append('    .word 0x%08X' % _guard_lo(i))
    L.append('k3_scratch:')
    n_res = _stream.RESERVED_TAIL // 4
    for i in range(_stream.SCRATCH_WORDS):
        if i >= _stream.SCRATCH_WORDS - n_res:
            # The reserved tail: word ARMED_OFF/4 is the DYNAMIC arm counter the
            # body increments, so it must start at zero on both sides.  Excluded
            # from every random offset window (stream.USABLE_BYTES).
            L.append('    .word 0x00000000        # reserved (offset %d)'
                     % (i * 4))
        else:
            L.append('    .word 0x%08X' % rng.next_u32())
    L.append('k3_guard_hi:')
    for i in range(_stream.GUARD_WORDS):
        L.append('    .word 0x%08X' % _guard_hi(i))
    if builder.irq_sites:
        L.append('    .align 2')
        L.append('k3_irq_count:')
        L.append('    .word 0')
    L.append('')
    return '\n'.join(L) + '\n'
